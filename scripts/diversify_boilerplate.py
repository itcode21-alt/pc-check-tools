DRY_RUN = '--apply' not in sys.argv

files = sorted(glob.glob('error-code-*.html'))
changed = 0
per_sentence_changed = {k: 0 for k in VARIANTS}

for fp in files:
    with open(fp, encoding='utf-8') as f:
        html = f.read()
    original = html
    for sentence, variants in VARIANTS.items():
        if sentence not in html:
            continue
        h = hashlib.sha256((fp + sentence[:20]).encode('utf-8')).hexdigest()
        idx = int(h, 16) % len(variants)
        chosen = variants[idx]
        if chosen != sentence:
            html = html.replace(sentence, chosen)
            per_sentence_changed[sentence] += 1
    if html != original:
        changed += 1
        if not DRY_RUN:
            with open(fp, 'w', encoding='utf-8') as f:
                f.write(html)

print(f"{'would change' if DRY_RUN else 'changed'}: {changed} files")
for k, v in per_sentence_changed.items():
    print(f"  replaced in {v} files: {k[:50]}...")
